  const LANG_LABELS = { en: "EN", fr: "FR", de: "DE" };
  let currentLang = "en";

  function t(key, vars) {
    const dict = I18N[currentLang] || I18N.en;
    let str = dict[key] !== undefined ? dict[key] : I18N.en[key] || key;
    if (vars) {
      for (const k of Object.keys(vars)) {
        str = str.split(`{${k}}`).join(vars[k]);
      }
    }
    return str;
  }

  function detectInitialLang() {
    try {
      const saved = window.localStorage.getItem("gf-lang");
      if (saved && I18N[saved]) return saved;
    } catch (e) { /* localStorage unavailable */ }
    const nav = (navigator.language || "en").slice(0, 2).toLowerCase();
    return I18N[nav] ? nav : "en";
  }

  // Small accessors so nav.js's setLang() can update the active language
  // without reaching into I18N/LANG_LABELS/currentLang directly — those
  // stay private to this file's IIFE.
  function hasLang(lang) {
    return !!I18N[lang];
  }
  function setCurrentLang(lang) {
    currentLang = I18N[lang] ? lang : "en";
  }
  function langLabel(lang) {
    return LANG_LABELS[lang] || LANG_LABELS.en;
  }

  window.GF = window.GF || {};
  Object.assign(window.GF, {
    t,
    detectInitialLang,
    hasLang,
    setCurrentLang,
    langLabel,
  });
